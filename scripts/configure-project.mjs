import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createAllowedOrigins, parseOrigin } from '../functions/src/config/project.ts'
import { integrationSettings, loadProjectEnvironment, validateProjectEnvironment } from './project-environment.mjs'

const env = loadProjectEnvironment()
const { site, functions, publicNames } = validateProjectEnvironment(env)
const json = value => `${JSON.stringify(value, null, 2)}\n`
const optionalPublic = ['NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID', 'NEXT_PUBLIC_RECAPTCHA_SITE_KEY', 'NEXT_PUBLIC_SOCIAL_PROFILES', 'GOOGLE_SITE_VERIFICATION']
const hostingEnv = [
  ...[...publicNames, ...optionalPublic].filter(name => env[name]).map(variable => ({ variable, value: env[variable], availability: ['BUILD', 'RUNTIME'] })),
  ...Object.entries(integrationSettings(env)).map(([variable, value]) => ({ variable, value, availability: ['RUNTIME'] })),
  { variable: 'POLAR_ACCESS_TOKEN', secret: 'polar-access-token', availability: ['RUNTIME'] },
  { variable: 'OPENAI_API_KEY', secret: 'openai-api-key', availability: ['RUNTIME'] },
]
// Serialize only explicitly selected settings. Credentials and debug tokens never enter this file.
const hosting = ['# Generated by npm run configure. Contains public settings and Secret Manager references.',
  'runConfig:', '  runtime: nodejs24', '  concurrency: 80', '  cpu: 1', '  memoryMiB: 1024', '  minInstances: 0', '  maxInstances: 50', '', 'env:',
  ...hostingEnv.flatMap(({ variable, value, secret, availability }) => [
    `  - variable: ${variable}`, `    ${secret ? 'secret' : 'value'}: ${JSON.stringify(secret ?? value)}`,
    '    availability:', ...availability.map(item => `      - ${item}`), '',
  ]),
].join('\n')
const managedFunctions = {
  NEXT_PUBLIC_APP_URL: site.appUrl,
  NEXT_PUBLIC_PUBLISHED_SITE_URL: site.publishedSiteUrl,
  NEXT_PUBLIC_SUPPORT_EMAIL: site.supportEmail,
  NEXT_PUBLIC_FIREBASE_FUNCTIONS_REGION: functions.region,
  CORS_EXTRA_ORIGINS: env.CORS_EXTRA_ORIGINS ?? '',
}
createAllowedOrigins(site, managedFunctions.CORS_EXTRA_ORIGINS)
const managedNames = new Set(['NEXT_APP_URL', ...Object.keys(managedFunctions)])
// Match whole assignments, including quoted multiline values, before replacing managed keys.
const previous = existsSync('functions/.env') ? readFileSync('functions/.env', 'utf8').replaceAll('\r\n', '\n').replace(
  /^[\t ]*(?:export[\t ]+)?([\w.-]+)[\t ]*=[\t ]*(?:"[^"]*"|'[^']*'|`[^`]*`|[^\n]*)[^\n]*(?:\n|$)/gm,
  (entry, name) => managedNames.has(name) ? '' : entry,
).trim() : ''
const firebase = JSON.parse(readFileSync('firebase.json', 'utf8'))
firebase.firestore.location = env.FIRESTORE_LOCATION
const firebaseRc = existsSync('.firebaserc') ? JSON.parse(readFileSync('.firebaserc', 'utf8')) : {}
firebaseRc.projects = { ...firebaseRc.projects, default: functions.projectId }
const origins = [site.appUrl, site.publishedSiteUrl, ...(env.CORS_EXTRA_ORIGINS ?? '').split(',').map(origin => origin.trim()).filter(Boolean).map(origin => parseOrigin(origin, 'CORS_EXTRA_ORIGINS'))]
const outputs = {
  'apphosting.yaml': hosting,
  '.firebaserc': json(firebaseRc),
  'firebase.json': json(firebase),
  'storage-cors.json': json([{ origin: [...new Set(origins)], method: ['PUT', 'GET', 'HEAD', 'OPTIONS'], responseHeader: ['Content-Type', 'Authorization', 'X-Goog-*', 'x-goog-*'], maxAgeSeconds: 3600 }]),
  'functions/.env': `${previous ? previous + '\n\n' : ''}${Object.entries(managedFunctions).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join('\n')}\n`,
}
if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([file, content]) => !existsSync(file) || readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content.replaceAll('\r\n', '\n')).map(([file]) => file)
  if (stale.length) throw new Error(`Configuration needs regeneration: ${stale.join(', ')}. Run npm run configure.`)
  console.log('Generated configuration is current.')
} else {
  for (const [file, content] of Object.entries(outputs)) writeFileSync(file, content)
  console.log(`Prepared local configuration for Firebase project ${functions.projectId}. No cloud resources were changed.`)
}
